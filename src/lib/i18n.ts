export const dictionaries: Record<Locale, Dict> = { es, fr };

export function isLocale(v: unknown): v is Locale {
  return v === "fr" || v === "es";
}

export function dict(locale: Locale | string | undefined): Dict {
  return dictionaries[isLocale(locale) ? locale : "es"];
}

export function activityForLocale(current: string, next: Locale): string {
  if (!current.trim() || current === DEFAULT_ACTIVITY.fr || current === DEFAULT_ACTIVITY.es) {
    return DEFAULT_ACTIVITY[next];
  }
  return current;
}
